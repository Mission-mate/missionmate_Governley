#!/usr/bin/env node
/**
 * Generates the database layer from the entity definitions in schema/entities/*.jsonc
 * (the JSON schemas exported from Base44).
 *
 * Outputs:
 *   supabase/migrations/20261122000200_entity_tables.sql   one table per entity
 *   supabase/migrations/20261122000300_entity_rls.sql      row level security policies
 *   supabase/functions/_shared/b44/schema.generated.js     column map used by the data adapter
 *   docs/DATABASE.md                                       human readable table list
 *
 * Run again after changing a file in schema/entities:  npm run db:generate
 * Then create a NEW migration for the change (never edit a migration that already ran).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENT_DIR = path.join(ROOT, 'schema/entities');

// ---------------------------------------------------------------- names
const TABLE_OVERRIDES = {
  User: 'users',
  ConflictOfInterest: 'conflicts_of_interest',
  StrategyLevel2: 'strategy_level2_pillars',
};

export const snake = (s) =>
  s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2').toLowerCase();

function plural(word) {
  if (/person$/.test(word)) return word.replace(/person$/, 'people');
  if (/[^aeiou]y$/.test(word)) return word.replace(/y$/, 'ies');
  if (/(s|x|ch|sh)$/.test(word)) return `${word}es`;
  return `${word}s`;
}

export const tableName = (entity) => TABLE_OVERRIDES[entity] || plural(snake(entity));

// ---------------------------------------------------------------- types
// kind is what the adapter needs to know; sql is the Postgres type.
function columnType(prop) {
  const t = Array.isArray(prop.type) ? prop.type.find((x) => x !== 'null') : prop.type;
  if (t === 'string' && prop.format === 'date') return { kind: 'date', sql: 'date' };
  if (t === 'string' && prop.format === 'date-time') return { kind: 'timestamp', sql: 'timestamptz' };
  if (t === 'string') return { kind: 'text', sql: 'text' };
  if (t === 'integer') return { kind: 'number', sql: 'bigint' };
  if (t === 'number') return { kind: 'number', sql: 'numeric' };
  if (t === 'boolean') return { kind: 'boolean', sql: 'boolean' };
  if (t === 'array') return { kind: 'array', sql: 'jsonb' };
  if (t === 'object') return { kind: 'json', sql: 'jsonb' };
  throw new Error(`Unknown type ${JSON.stringify(prop)}`);
}

const q = (id) => `"${id.replace(/"/g, '""')}"`;
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

function sqlDefault(prop, sqlType) {
  if (!('default' in prop) || prop.default === null) return '';
  const v = prop.default;
  if (sqlType === 'jsonb') return ` default ${lit(JSON.stringify(v))}::jsonb`;
  if (typeof v === 'boolean') return ` default ${v}`;
  if (typeof v === 'number') return ` default ${v}`;
  return ` default ${lit(v)}`;
}

// Columns every entity record has (same names Base44 used, so the app code keeps working).
const SYSTEM_COLUMNS = [
  ['id', 'text primary key default public.new_id()', 'text'],
  ['created_date', 'timestamptz not null default now()', 'timestamp'],
  ['updated_date', 'timestamptz not null default now()', 'timestamp'],
  ['created_by', 'text', 'text'],
  ['created_by_id', 'text', 'text'],
  ['is_sample', 'boolean not null default false', 'boolean'],
  ['_extra', "jsonb not null default '{}'::jsonb", 'json'],
];

// Extra columns the users table has on top of User.jsonc (Base44 built-in user fields).
const USER_BUILTIN = {
  email: { type: 'string', description: 'Login email (copied from auth.users)' },
  full_name: { type: 'string', description: 'Display name' },
  phone: { type: 'string', description: 'Phone number (My Profile)' },
  theme: { type: 'string', description: 'Appearance preference: light / dark / system' },
};

// ---------------------------------------------------------------- read entities
const entities = fs
  .readdirSync(ENT_DIR)
  .filter((f) => f.endsWith('.jsonc'))
  .sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(ENT_DIR, f), 'utf8').replace(/^\s*\/\/.*$/gm, '')));

const tableNames = new Map();
for (const e of entities) {
  const t = tableName(e.name);
  if (tableNames.has(t)) throw new Error(`Table name clash: ${e.name} and ${tableNames.get(t)} -> ${t}`);
  tableNames.set(t, e.name);
}

// ---------------------------------------------------------------- tables SQL
const header = (title) => `-- ${title}
-- GENERATED by scripts/generate-schema.mjs from schema/entities/*.jsonc — do not edit by hand.
-- To change the database later, edit the entity file, re-run the generator, and add a NEW migration.
`;

let tablesSql = header('Entity tables (one table per Base44 entity)');
tablesSql += `
-- Notes
--  * Field names are kept exactly as in Base44 so the existing app code works unchanged.
--  * "required" and "enum" rules from Base44 are written as column comments, not hard constraints,
--    so existing records and screens are not blocked. Tighten them later once the app is tested.
--  * _extra holds any field the app saves that is not in the schema (safety net, normally empty).
`;

const schemaMap = {};
const docRows = [];

for (const e of entities) {
  const table = tableName(e.name);
  const isUser = e.name === 'User';
  const props = isUser ? { ...USER_BUILTIN, ...e.properties } : e.properties;
  const required = new Set(e.required || []);
  const columns = {};
  for (const [name, , kind] of SYSTEM_COLUMNS) columns[name] = kind;

  if (isUser) {
    // The users table is created in the core migration (linked to auth.users). Only record the map here.
    for (const [name, prop] of Object.entries(props)) columns[name] = columnType(prop).kind;
    columns.id = 'text';
    delete columns.is_sample;
    delete columns.created_by;
    delete columns.created_by_id;
    schemaMap[e.name] = { table, columns, required: [...required] };
    docRows.push({ entity: e.name, table, count: Object.keys(props).length, desc: 'Team members (linked to Supabase Auth users)' });
    continue;
  }

  const lines = SYSTEM_COLUMNS.map(([name, def]) => `  ${q(name)} ${def}`);
  const comments = [];
  for (const [name, prop] of Object.entries(props)) {
    if (columns[name]) throw new Error(`${e.name}.${name} clashes with a system column`);
    const { kind, sql } = columnType(prop);
    columns[name] = kind;
    lines.push(`  ${q(name)} ${sql}${sqlDefault(prop, sql)}`);
    const notes = [];
    if (required.has(name)) notes.push('REQUIRED');
    if (prop.enum) notes.push(`one of: ${prop.enum.join(' | ')}`);
    if (prop.description) notes.push(prop.description);
    if (notes.length) comments.push(`comment on column public.${q(table)}.${q(name)} is ${lit(notes.join(' — '))};`);
  }

  tablesSql += `
-- ${e.name}
create table if not exists public.${q(table)} (
${lines.join(',\n')}
);
comment on table public.${q(table)} is ${lit(`Base44 entity: ${e.name}`)};
${comments.join('\n')}
create trigger ${q(`${table}_touch`)} before insert or update on public.${q(table)}
  for each row execute function public.b44_touch();
create index if not exists ${q(`${table}_created_date_idx`)} on public.${q(table)} (created_date desc);
`;
  // Indexes on link fields (anything ending in _id) and on the polymorphic owner pairs.
  const names = Object.keys(props);
  for (const name of names) {
    if (/_id$/.test(name) && columns[name] === 'text') {
      tablesSql += `create index if not exists ${q(`${table}_${name}_idx`)} on public.${q(table)} (${q(name)});\n`;
    }
    if (/_ids$/.test(name) && columns[name] === 'array') {
      tablesSql += `create index if not exists ${q(`${table}_${name}_gin`)} on public.${q(table)} using gin (${q(name)});\n`;
    }
  }
  for (const [a, b] of [['object_type', 'object_id'], ['parent_type', 'parent_id']]) {
    if (names.includes(a) && names.includes(b)) {
      tablesSql += `create index if not exists ${q(`${table}_${a}_${b}_idx`)} on public.${q(table)} (${q(a)}, ${q(b)});\n`;
    }
  }
  schemaMap[e.name] = { table, columns, required: [...required] };
  docRows.push({ entity: e.name, table, count: names.length, desc: (e.description || '').split('\n')[0] });
}

// ---------------------------------------------------------------- RLS
// Base44 rules: null / {} = any signed-in user; user_condition.role = app role; server_only = edge functions only.
function rlsExpr(rule, entity) {
  if (rule === null || rule === undefined) return 'true';
  if (typeof rule !== 'object') throw new Error(`Bad rule on ${entity}`);
  const keys = Object.keys(rule);
  if (keys.length === 0) return 'true';
  const parts = keys.map((k) => {
    const v = rule[k];
    if (k === '$or') return `(${v.map((r) => rlsExpr(r, entity)).join(' or ')})`;
    if (k === '$and') return `(${v.map((r) => rlsExpr(r, entity)).join(' and ')})`;
    if (k === 'user_condition') {
      if (v.role === 'server_only') return null; // no client access at all
      if (v.role) return `(select public.current_user_role()) = ${lit(v.role)}`;
      throw new Error(`Unsupported user_condition on ${entity}: ${JSON.stringify(v)}`);
    }
    if (k.startsWith('data.')) {
      const col = k.slice(5);
      const kind = schemaMap[entity].columns[col];
      if (v === '{{user.id}}') {
        return kind === 'array' ? `${q(col)} ? (select auth.uid())::text` : `${q(col)} = (select auth.uid())::text`;
      }
      if (v && typeof v === 'object' && '$ne' in v) return `${q(col)} is distinct from ${lit(v.$ne)}`;
      if (typeof v === 'string') return `${q(col)} = ${lit(v)}`;
      throw new Error(`Unsupported data rule on ${entity}: ${k}=${JSON.stringify(v)}`);
    }
    throw new Error(`Unsupported rule key on ${entity}: ${k}`);
  });
  if (parts.includes(null)) return null;
  return parts.length === 1 ? parts[0] : `(${parts.join(' and ')})`;
}

let rlsSql = header('Row level security for entity tables');
rlsSql += `
-- Every policy also requires an active team member: (select public.is_member()).
-- Users with status 'pending' (signed up on their own, not yet approved) or 'suspended' have no data access.
-- Edge functions that use the service role key bypass these rules (same as Base44 asServiceRole).
`;
for (const e of entities) {
  if (e.name === 'User') continue;
  const table = tableName(e.name);
  const rls = e.rls || {};
  rlsSql += `\nalter table public.${q(table)} enable row level security;\n`;
  // Explicit grants: signed-in users go through the policies below; anonymous visitors get nothing.
  rlsSql += `revoke all on public.${q(table)} from anon;\n`;
  rlsSql += `grant select, insert, update, delete on public.${q(table)} to authenticated;\n`;
  rlsSql += `grant all on public.${q(table)} to service_role;\n`;
  const ops = { read: 'select', create: 'insert', update: 'update', delete: 'delete' };
  for (const [b44op, sqlop] of Object.entries(ops)) {
    const expr = rlsExpr(rls[b44op], e.name);
    if (expr === null) {
      rlsSql += `-- ${table} ${sqlop}: server only (only edge functions using the service role can do this)\n`;
      continue;
    }
    const cond = expr === 'true' ? '(select public.is_member())' : `(select public.is_member()) and ${expr}`;
    const name = q(`${table}_${sqlop}`);
    if (sqlop === 'select' || sqlop === 'delete') {
      rlsSql += `create policy ${name} on public.${q(table)} for ${sqlop} to authenticated using (${cond});\n`;
    } else if (sqlop === 'insert') {
      rlsSql += `create policy ${name} on public.${q(table)} for insert to authenticated with check (${cond});\n`;
    } else {
      rlsSql += `create policy ${name} on public.${q(table)} for update to authenticated using (${cond}) with check (${cond});\n`;
    }
  }
}

// ---------------------------------------------------------------- write files
const write = (rel, content) => {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
  console.log('wrote', rel);
};

write('supabase/migrations/20261122000200_entity_tables.sql', tablesSql);
write('supabase/migrations/20261122000300_entity_rls.sql', rlsSql);
write(
  'supabase/functions/_shared/b44/schema.generated.js',
  `// GENERATED by scripts/generate-schema.mjs — do not edit by hand.
// Entity name -> table name and column kinds. Used by the data adapter (entities.js)
// in both the browser app and the edge functions.
export const SCHEMA = ${JSON.stringify(schemaMap, null, 2)};
`,
);

let doc = `# Database tables

Generated from \`schema/entities\`. ${entities.length} entities → ${entities.length} tables in the \`public\` schema.

Every table also has: \`id\` (text, 24-char hex), \`created_date\`, \`updated_date\`, \`created_by\` (email),
\`created_by_id\` (user id), \`is_sample\`, \`_extra\` (jsonb safety net).

| Base44 entity | Supabase table | Fields |
|---|---|---|
`;
for (const r of docRows) doc += `| ${r.entity} | \`${r.table}\` | ${r.count} |\n`;
write('docs/DATABASE.md', doc);
